#!/usr/bin/env python3
"""Generate a linked table of contents for the v1, v2, and distributed specs."""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "platform_specs_table_of_contents.md"
SPECS = (
    ROOT / "platform_specs_v1.md",
    ROOT / "platform_specs_v2.md",
    ROOT / "platform_specs_distributed_execution.md",
)
HEADING = re.compile(r"^(#{1,6})[ \t]+(.+?)[ \t]*#*[ \t]*$")
FENCE = re.compile(r"^[ \t]{0,3}(`{3,}|~{3,})")
INLINE_LINK = re.compile(r"!?\[([^]]+)\]\([^)]+\)")
HTML_TAG = re.compile(r"<[^>]+>")


def heading_text(raw: str) -> str:
    """Reduce common Markdown formatting to the visible heading text."""
    raw = INLINE_LINK.sub(r"\1", raw)
    raw = HTML_TAG.sub("", raw)
    return raw.replace("`", "").replace("*", "").replace("_", "")


def github_slug(title: str) -> str:
    """Match GitHub heading anchors for the punctuation used by these specs."""
    plain = heading_text(title).lower()
    plain = re.sub(r"[^\w\s-]", "", plain, flags=re.UNICODE)
    return re.sub(r"\s", "-", plain)


def headings(source: Path) -> list[tuple[int, str, str]]:
    result: list[tuple[int, str, str]] = []
    slugs: Counter[str] = Counter()
    fence_char = ""
    fence_width = 0

    for line in source.read_text(encoding="utf-8").splitlines():
        fence = FENCE.match(line)
        if fence:
            marker = fence.group(1)
            if not fence_char:
                fence_char, fence_width = marker[0], len(marker)
            elif marker[0] == fence_char and len(marker) >= fence_width:
                fence_char, fence_width = "", 0
            continue
        if fence_char:
            continue
        match = HEADING.match(line)
        if not match:
            continue
        level, title = len(match.group(1)), match.group(2).strip()
        slug = github_slug(title)
        occurrence = slugs[slug]
        slugs[slug] += 1
        if occurrence:
            slug = f"{slug}-{occurrence}"
        result.append((level, title, slug))

    return result


def render() -> str:
    lines = [
        "# Platform specifications table of contents",
        "",
        "Generated by `python3 scripts/generate_specs_toc.py`. Run the script after editing the source headings.",
        "",
    ]
    for source in SPECS:
        entries = headings(source)
        if not entries or entries[0][0] != 1:
            raise ValueError(f"Expected a level-one title in {source.name}")
        _, title, slug = entries[0]
        lines.extend((f"## [{title}]({source.name}#{slug})", ""))
        for level, heading, anchor in entries[1:]:
            indent = "  " * (level - 2)
            lines.append(f"{indent}- [{heading}]({source.name}#{anchor})")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the generated document is stale")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            print(f"Out of date: {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print(f"Up to date: {OUTPUT.relative_to(ROOT)}")
        return 0
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
